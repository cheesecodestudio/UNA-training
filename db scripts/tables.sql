CREATE TABLE usuario (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(120 CHAR) NOT NULL,
  correo VARCHAR2(180 CHAR) NOT NULL,
  tipo VARCHAR2(20 CHAR) NOT NULL,
  activo NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT uq_usuario_correo UNIQUE (correo),
  CONSTRAINT ck_usuario_tipo CHECK (tipo IN ('ESTUDIANTE','DOCENTE')),
  CONSTRAINT ck_usuario_activo CHECK (activo IN (0,1))
);

CREATE TABLE equipo (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR2(30 CHAR) NOT NULL,
  nombre VARCHAR2(120 CHAR) NOT NULL,
  activo NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT uq_equipo_codigo UNIQUE (codigo),
  CONSTRAINT ck_equipo_activo CHECK (activo IN (0,1))
);

CREATE TABLE reserva (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id NUMBER(19) NOT NULL,
  equipo_id NUMBER(19) NOT NULL,
  inicio TIMESTAMP NOT NULL,
  fin TIMESTAMP NOT NULL,
  estado VARCHAR2(12 CHAR) DEFAULT 'ACTIVA' NOT NULL,
  CONSTRAINT fk_reserva_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
  CONSTRAINT fk_reserva_equipo FOREIGN KEY (equipo_id) REFERENCES equipo(id),
  CONSTRAINT ck_reserva_fechas CHECK (fin > inicio),
  CONSTRAINT ck_reserva_estado CHECK (estado IN ('ACTIVA','CANCELADA'))
);
CREATE INDEX ix_reserva_equipo_horario
  ON reserva (equipo_id, estado, inicio, fin);
CREATE INDEX ix_reserva_usuario ON reserva (usuario_id);